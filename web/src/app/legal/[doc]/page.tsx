const UPDATED = "ปรับปรุงล่าสุด 23 ตุลาคม 2569";

export async function generateStaticParams() {
  return Object.keys(DOCS).map((doc) => ({ doc }));
}
export const dynamicParams = true;

type Props = { params: Promise<{ doc: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { doc } = await params;
  const d = DOCS[doc];
  if (!d) return {};
  return pageMetadata({ url: U.legal(doc), title: `${d.title} · AiLakorn`, desc: d.desc });
}

export default async function LegalPage({ params }: Props) {
  const { doc } = await params;
  const d = DOCS[doc];
  if (!d) notFound();
  const c = await getCatalog();
  return (
    <Shell c={c} narrow>
      <JsonLd data={breadcrumbLd(c, [["หน้าแรก", U.home], ["ข้อกำหนด", U.legal(doc)], [d.title, U.legal(doc)]])} />
      <Crumbs items={[["หน้าแรก", U.home], [d.title, null]]} />
      <PageHead h1={d.title} sub={UPDATED} />
      <div className="prose">
        {d.sections.map(([h, ps], i) => (
          <Fragment key={i}>
            <h2 id={`s${i + 1}`}>{i + 1}. {h}</h2>
            {ps.map((p, j) => <p key={j}>{p}</p>)}
          </Fragment>
        ))}
      </div>
    </Shell>
  );
}
